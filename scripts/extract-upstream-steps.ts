#!/usr/bin/env bun
/**
 * Reads ci/upstream/ci.yml and writes scripts/upstream-test.sh containing every
 * run: block from jobs.test and jobs.cross-compile (matrix in file order).
 * Local leg: docker run --rm --cpus=2 -v $PWD:/w -w /w/upstream golang:1.26.9
 */
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parse as parseYaml } from "yaml";

const root = join(import.meta.dir, "..");
const yamlPath = join(root, "ci", "upstream", "ci.yml");
const outPath = join(root, "scripts", "upstream-test.sh");
const PIN = "1672852136fc87748249d22bce0819f33419ea79";

type Step = {
  name?: string;
  uses?: string;
  run?: string;
  env?: Record<string, string>;
};

type Job = {
  steps?: Step[];
  strategy?: { matrix?: { include?: Array<{ goos: string; goarch: string }> } };
};

type Workflow = { jobs?: Record<string, Job> };

function shellEscapeSingle(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function emitRun(step: Step, lines: string[]): void {
  const name = (step.name ?? "run").replace(/'/g, "");
  lines.push(`echo '==> ${name}'`);
  if (step.env) {
    for (const [k, v] of Object.entries(step.env)) {
      lines.push(`export ${k}=${shellEscapeSingle(String(v))}`);
    }
  }
  lines.push("(");
  for (const line of (step.run ?? "").split("\n")) {
    lines.push(`  ${line}`);
  }
  lines.push(")");
  lines.push("");
}

async function main(): Promise<void> {
  const text = await readFile(yamlPath, "utf8");
  const doc = parseYaml(text) as Workflow;
  const testJob = doc.jobs?.test;
  const crossJob = doc.jobs?.["cross-compile"];
  if (!testJob?.steps) throw new Error("missing jobs.test");
  if (!crossJob?.steps) throw new Error("missing jobs.cross-compile");

  const matrix = crossJob.strategy?.matrix?.include ?? [
    { goos: "linux", goarch: "arm64" },
    { goos: "darwin", goarch: "amd64" },
    { goos: "darwin", goarch: "arm64" },
    { goos: "windows", goarch: "amd64" },
    { goos: "windows", goarch: "arm64" },
  ];

  const innerTest: string[] = [];
  innerTest.push("#!/usr/bin/env bash");
  innerTest.push("set -euo pipefail");
  innerTest.push("git config --global --replace-all safe.directory '*'");
  innerTest.push("");
  for (const step of testJob.steps) {
    if (!step.run) continue;
    if (step.name === "Trust workspace") continue;
    emitRun(step, innerTest);
  }

  const lines: string[] = [];
  lines.push("#!/usr/bin/env bash");
  lines.push("# GENERATED by bun run scripts/extract-upstream-steps.ts — do not edit by hand.");
  lines.push("set -euo pipefail");
  lines.push('ROOT="$(cd "$(dirname "$0")/.." && pwd)"');
  lines.push('cd "$ROOT"');
  lines.push(`PIN="${PIN}"`);
  lines.push('actual="$(git -C upstream rev-parse HEAD)"');
  lines.push('if [[ "$actual" != "$PIN" ]]; then');
  lines.push('  echo "upstream pin mismatch: $actual" >&2');
  lines.push("  exit 1");
  lines.push("fi");
  lines.push("");
  lines.push("if ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then");
  lines.push(
    '  echo "docker not available; run upstream jobs via GitHub Actions .github/workflows/upstream-ci.yml" >&2',
  );
  lines.push("  exit 1");
  lines.push("fi");
  lines.push("");
  lines.push('INNER_TEST="$(mktemp)"');
  lines.push('INNER_CROSS=""');
  lines.push('trap \'rm -f "$INNER_TEST"; [[ -n "$INNER_CROSS" ]] && rm -f "$INNER_CROSS"\' EXIT');
  lines.push(`cat > "$INNER_TEST" <<'EOF_TEST'`);
  lines.push(...innerTest);
  lines.push("EOF_TEST");
  lines.push("");
  lines.push('echo "==== job: test (docker golang:1.26.9) ===="');
  lines.push(
    'docker run --rm --cpus=2 -v "$ROOT:/w" -v "$INNER_TEST:/tmp/run-test.sh:ro" -w /w/upstream golang:1.26.9 bash /tmp/run-test.sh',
  );
  lines.push("");

  for (const leg of matrix) {
    const innerCross: string[] = [];
    innerCross.push("#!/usr/bin/env bash");
    innerCross.push("set -euo pipefail");
    innerCross.push("git config --global --replace-all safe.directory '*'");
    innerCross.push(`export GOOS=${leg.goos}`);
    innerCross.push(`export GOARCH=${leg.goarch}`);
    innerCross.push("export CGO_ENABLED=0");
    innerCross.push("");
    for (const step of crossJob.steps) {
      if (!step.run) continue;
      if (step.name === "Trust workspace") continue;
      emitRun(step, innerCross);
    }
    lines.push(`echo "==== job: cross-compile ${leg.goos}/${leg.goarch} ===="`);
    lines.push('INNER_CROSS="$(mktemp)"');
    lines.push(`cat > "$INNER_CROSS" <<'EOF_CROSS'`);
    lines.push(...innerCross);
    lines.push("EOF_CROSS");
    lines.push(
      'docker run --rm --cpus=2 -v "$ROOT:/w" -v "$INNER_CROSS:/tmp/run-cross.sh:ro" -w /w/upstream golang:1.26.9 bash /tmp/run-cross.sh',
    );
    lines.push("");
  }

  lines.push('echo "upstream-test.sh finished ok"');
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, `${lines.join("\n")}\n`, "utf8");
  await chmod(outPath, 0o755);
  console.log(`wrote ${outPath}`);
}

await main();
